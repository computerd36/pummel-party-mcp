<#
.SYNOPSIS
  Prepares a release of pummel-party-mcp: checks, builds, tests and packages. PREPARES ONLY: nothing is published.

.DESCRIPTION
  Steps (stops at the first failure):
    1. The working tree is clean (git status), unless -AllowDirty.
    2. Every version number agrees with -Version (csproj, PluginInfo.cs, package.json, package-lock.json,
       docs\plugin-api.md title, CHANGELOG.md heading). Mismatches are reported; no file is edited.
       The two changelog files must be identical. The Thunderstore manifest is generated by
       package-thunderstore.ps1 from the csproj version, so there is no manifest file to check.
    3. Builds the plugin (Release).
    4. Runs the three test suites: Plugin.Tests, Plugin.PatchTests (needs the game's assemblies) and the server tests.
    5. Runs scripts\package-thunderstore.ps1 (zip) and copies the zip into release-out\.
    6. Runs npm pack into release-out\ (the tarball).
    7. Prints the SHA-256 of the zip and the tarball and the manual steps that remain.

  It never calls npm publish, git push or git tag, never uploads anything and never writes into the game folder.
  Everything it writes is inside the repo: bin/obj/dist/artifacts (gitignored, as for any build) and release-out\
  (gitignored). Build tools keep their own caches (NuGet, npm) outside the repo, as usual.
  There is deliberately no -Bump option: the version lives in free text too (docs, changelog heading), so the
  maintainer edits the files by hand (see docs\release-checklist.md) and this script verifies them.
  Windows PowerShell 5.1 compatible.

.PARAMETER Version
  The release version (MAJOR.MINOR.PATCH), for example 1.0.0.

.PARAMETER GameDir
  Game install folder, passed to the plugin build and the patch tests as -p:GameDir. When omitted the projects
  resolve it themselves (src\GameDir.props.user, else the standard Steam location). It is only read.

.PARAMETER ContinueOnVersionMismatch
  Report version mismatches but carry on (only for testing this script; never release this way).

.PARAMETER AllowDirty
  Continue with uncommitted changes (for testing the script; do not release from a dirty tree).

.EXAMPLE
  .\scripts\prepare-release.ps1 -Version 1.0.0
  .\scripts\prepare-release.ps1 -Version 1.0.0 -AllowDirty -ContinueOnVersionMismatch   # testing only: skips the clean-tree and version checks
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Version,
    [string]$GameDir,
    [switch]$AllowDirty,
    [switch]$ContinueOnVersionMismatch
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# A trailing backslash would escape the closing quote of -p:GameDir="...\" when the argument is passed on.
if ($GameDir) { $GameDir = $GameDir.TrimEnd('\', '/') }

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$serverDir = Join-Path $repo 'src\PummelPartyMcp.Server'
$pluginCsproj = Join-Path $repo 'src\PummelPartyMcp.Plugin\PummelPartyMcp.Plugin.csproj'
$outDir = Join-Path $repo 'release-out'
$zipName = "PummelPartyMcp-$Version.zip"
$tgzName = "pummel-party-mcp-$Version.tgz"
$warnings = New-Object System.Collections.Generic.List[string]

function Write-Step([string]$text) { Write-Host ''; Write-Host "== $text" -ForegroundColor Cyan }
function Invoke-Checked([string]$what, [scriptblock]$block) {
    & $block
    if ($LASTEXITCODE -ne 0) { throw "$what failed (exit code $LASTEXITCODE)." }
}

if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "-Version must be MAJOR.MINOR.PATCH (got '$Version')." }

# --- tools
$git = Get-Command git -ErrorAction SilentlyContinue
if (-not $git) { throw 'git was not found on PATH.' }
$dotnetCmd = Get-Command dotnet -ErrorAction SilentlyContinue
if (-not $dotnetCmd) {
    $fallback = 'C:\Program Files\dotnet\dotnet.exe'
    if (Test-Path -LiteralPath $fallback -PathType Leaf) {
        # Only this process sees the changed PATH (package-thunderstore.ps1 needs dotnet on PATH).
        $env:PATH = (Split-Path -Parent $fallback) + ';' + $env:PATH
        $dotnetCmd = Get-Command dotnet -ErrorAction SilentlyContinue
    }
}
if (-not $dotnetCmd) { throw 'dotnet (the .NET SDK) was not found on PATH or in C:\Program Files\dotnet.' }
$npmCmd = Get-Command npm -ErrorAction SilentlyContinue
if (-not $npmCmd) { throw 'npm (Node.js) was not found on PATH.' }

# --- 1. clean tree
Write-Step '1. Working tree'
$dirty = @(& git -C $repo status --porcelain)
if ($dirty.Count -gt 0) {
    if (-not $AllowDirty) { throw "The working tree has uncommitted changes (commit them, or pass -AllowDirty for a test run):`n$($dirty -join "`n")" }
    Write-Warning "Uncommitted changes present (-AllowDirty): $($dirty.Count) path(s). Do not release from this tree."
    $warnings.Add('The tree was dirty (-AllowDirty); rerun without it before releasing.')
}
else { Write-Host 'Clean.' }
$head = (& git -C $repo rev-parse --short HEAD)
Write-Host "HEAD: $head"

# --- 2. versions
Write-Step "2. Version numbers (expecting $Version)"
$mismatches = New-Object System.Collections.Generic.List[string]
function Test-Version([string]$label, [string]$found) {
    if ($found -eq $Version) { Write-Host ("  ok        {0}: {1}" -f $label, $found) }
    else { Write-Host ("  MISMATCH  {0}: {1}" -f $label, $found) -ForegroundColor Red; $mismatches.Add("$label is '$found'") }
}
function Read-Text([string]$rel) {
    $p = Join-Path $repo $rel
    if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { throw "Missing file: $rel" }
    return [System.IO.File]::ReadAllText($p)
}

[xml]$proj = Read-Text 'src\PummelPartyMcp.Plugin\PummelPartyMcp.Plugin.csproj'
$csprojVersion = '(not found)'
foreach ($pg in @($proj.Project.PropertyGroup)) {
    if ($pg.PSObject.Properties['Version'] -and $pg.Version) { $csprojVersion = ([string]$pg.Version).Trim() }
}
Test-Version 'plugin csproj <Version>' $csprojVersion

$m = [regex]::Match((Read-Text 'src\PummelPartyMcp.Plugin\PluginInfo.cs'), 'const\s+string\s+Version\s*=\s*"([^"]+)"')
Test-Version 'PluginInfo.cs Version' $(if ($m.Success) { $m.Groups[1].Value } else { '(not found)' })

$pkg = (Read-Text 'src\PummelPartyMcp.Server\package.json') | ConvertFrom-Json
Test-Version 'server package.json version' ([string]$pkg.version)

# Regex instead of ConvertFrom-Json: Windows PowerShell 5.1 cannot read the lock file's "" key reliably.
$lockText = Read-Text 'src\PummelPartyMcp.Server\package-lock.json'
$m = [regex]::Match($lockText, '(?m)^  "version":\s*"([^"]+)"')
Test-Version 'package-lock.json version' $(if ($m.Success) { $m.Groups[1].Value } else { '(not found)' })
$m = [regex]::Match($lockText, '(?s)"packages":\s*\{\s*"":\s*\{[^}]*?"version":\s*"([^"]+)"')
Test-Version 'package-lock.json packages[""].version' $(if ($m.Success) { $m.Groups[1].Value } else { '(not found)' })

$m = [regex]::Match((Read-Text 'docs\plugin-api.md'), '(?m)^#[^\r\n]*\(api v\d+, plugin (\d+\.\d+\.\d+)\)')
Test-Version 'docs\plugin-api.md title (plugin ...)' $(if ($m.Success) { $m.Groups[1].Value } else { '(not found)' })

# The changelog needs a heading for this version: "## [1.0.0] - date" or "## [Unreleased] - 1.0.0".
$cl = Read-Text 'CHANGELOG.md'
$vEsc = [regex]::Escape($Version)
if ($cl -match "(?m)^##\s+\[$vEsc\]" -or $cl -match "(?m)^##\s+\[Unreleased\]\s*-\s*$vEsc\s*$") { Write-Host "  ok        CHANGELOG.md has a heading for $Version" }
else { Write-Host "  MISMATCH  CHANGELOG.md has no heading for $Version" -ForegroundColor Red; $mismatches.Add("CHANGELOG.md has no heading for $Version") }
if ($cl -match '(?m)^##\s+\[Unreleased\]') { Write-Host "  note      CHANGELOG.md still says [Unreleased]; at release change the heading to '## [$Version] - <date>'."; $warnings.Add('CHANGELOG.md heading still says [Unreleased].') }

# The two changelog files are one text (line endings ignored).
$a = (Read-Text 'CHANGELOG.md') -replace "`r`n", "`n"
$b = (Read-Text 'packaging\thunderstore\CHANGELOG.md') -replace "`r`n", "`n"
if ($a -ceq $b) { Write-Host '  ok        packaging\thunderstore\CHANGELOG.md is identical to CHANGELOG.md' }
else { Write-Host '  MISMATCH  packaging\thunderstore\CHANGELOG.md differs from CHANGELOG.md (copy the root file over it)' -ForegroundColor Red; $mismatches.Add('the two changelog files differ') }

if ($pkg.PSObject.Properties['private'] -and $pkg.private -eq $true) {
    Write-Host '  note      package.json still has "private": true (npm refuses to publish it; the maintainer removes it at release).'
    $warnings.Add('package.json still has "private": true.')
}

if ($mismatches.Count -gt 0 -and $ContinueOnVersionMismatch) {
    Write-Warning "Version mismatches ignored (-ContinueOnVersionMismatch, for testing the script only): $($mismatches -join "; ")"
    $warnings.Add("Version mismatches were ignored (-ContinueOnVersionMismatch); do not release.")
}
elseif ($mismatches.Count -gt 0) {
    throw "Version check failed:`n  $($mismatches -join "`n  ")`nEdit the files by hand (list: docs\release-checklist.md) and run again. This script never edits them."
}

# --- 3. build the plugin
Write-Step '3. Build the plugin (Release)'
$buildArgs = @('build', $pluginCsproj, '-c', 'Release', '-nologo', '-v', 'q')
if ($GameDir) { $buildArgs += "-p:GameDir=$GameDir" }
Invoke-Checked 'dotnet build' { & dotnet @buildArgs }

# --- 4. tests
Write-Step '4a. Plugin.Tests (Unity-free core)'
Invoke-Checked 'Plugin.Tests' { & dotnet run -c Release --project (Join-Path $repo 'src\PummelPartyMcp.Plugin.Tests') }

Write-Step '4b. Plugin.PatchTests (drift test; reads the game assemblies for reflection only)'
$patchArgs = @('run', '-c', 'Release', '--project', (Join-Path $repo 'src\PummelPartyMcp.Plugin.PatchTests'))
if ($GameDir) { $patchArgs += "-p:GameDir=$GameDir" }
Invoke-Checked 'Plugin.PatchTests' { & dotnet @patchArgs }

Write-Step '4c. Server tests'
Invoke-Checked 'npm test' { & npm test --prefix $serverDir }

# --- 5. Thunderstore zip
Write-Step '5. Thunderstore package'
$pkgArgs = @{}
if ($GameDir) { $pkgArgs['GameDir'] = $GameDir }
if ($AllowDirty) { $pkgArgs['AllowDirty'] = $true }
& (Join-Path $PSScriptRoot 'package-thunderstore.ps1') @pkgArgs
$zipSrc = Join-Path $repo "artifacts\$zipName"
if (-not (Test-Path -LiteralPath $zipSrc -PathType Leaf)) { throw "Expected package not found: $zipSrc" }

# release-out must be inside the repo and ignored by git
if (-not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
& git -C $repo check-ignore -q -- 'release-out/'
if ($LASTEXITCODE -ne 0) { throw 'release-out/ is not git-ignored; add "/release-out/" to .gitignore first.' }
$zipOut = Join-Path $outDir $zipName
Copy-Item -LiteralPath $zipSrc -Destination $zipOut -Force

# --- 6. npm tarball
Write-Step '6. npm pack (no publish)'
$tgzOut = Join-Path $outDir $tgzName
if (Test-Path -LiteralPath $tgzOut) { Remove-Item -LiteralPath $tgzOut -Force }
Invoke-Checked 'npm pack' { & npm pack $serverDir --pack-destination $outDir --quiet }
if (-not (Test-Path -LiteralPath $tgzOut -PathType Leaf)) { throw "Expected tarball not found: $tgzOut" }

# --- 7. report
Write-Step '7. Result'
foreach ($f in @($zipOut, $tgzOut)) {
    $item = Get-Item -LiteralPath $f
    $hash = (Get-FileHash -LiteralPath $f -Algorithm SHA256).Hash.ToLowerInvariant()
    Write-Host ("{0}  ({1:N0} bytes)" -f $item.FullName, $item.Length)
    Write-Host ("  SHA-256  {0}" -f $hash)
}
if ($warnings.Count -gt 0) {
    Write-Host ''
    Write-Host 'Notes:' -ForegroundColor Yellow
    foreach ($w in $warnings) { Write-Host "  - $w" -ForegroundColor Yellow }
}
Write-Host ''
Write-Host 'Prepared only. Nothing was published, tagged, pushed or uploaded.' -ForegroundColor Green
Write-Host 'Manual steps that remain (details: docs\release-checklist.md):'
Write-Host '  - In the game: build with this DLL, run self_test (ok: true), do the in-game checks.'
Write-Host '  - Thunderstore: put the BepInEx dependency string into the manifest (package-thunderstore.ps1), validate the zip, upload by hand (a version can never be uploaded twice).'
Write-Host '  - GitHub: tag v<version>, create the release, attach the same zip and publish its SHA-256.'
Write-Host '  - npm: remove "private": true, npm publish --dry-run, then publish by hand (2FA), then check npx -y pummel-party-mcp from a clean folder.'
