        public static string[] AssetTypes => All.Select(f => f.AssetType).Distinct().ToArray();

        public static IEnumerable<ImportSettingField> ForType(string assetType) =>
            All.Where(f => string.Equals(f.AssetType, assetType, StringComparison.OrdinalIgnoreCase));

        public static string FieldNames(string assetType) => string.Join(", ", ForType(assetType).Select(f => f.Name).ToArray());

        /// <summary>
        /// Validates and normalises <paramref name="values"/> for an asset type before anything changes. <paramref name="current"/> gives the
        /// asset's current value as enum name or "true"/"false".
        /// </summary>
        public static ImportSettingsPlan Plan(string assetType, JObject values, Func<ImportSettingField, string> current)
        {
            List<ImportSettingField> fields = ForType(assetType).ToList();
            if (fields.Count == 0)
            {
                throw RpcException.InvalidParams($"{assetType} assets have no import settings in the editor (nothing to set)");
            }
            if (values == null || values.Count == 0)
            {
                throw RpcException.InvalidParams("'values' must be an object with at least one field; fields: " + FieldNames(assetType));
            }
            ImportSettingsPlan plan = new ImportSettingsPlan { AssetType = fields[0].AssetType };
            foreach (JProperty p in values.Properties())
            {
                ImportSettingField f = fields.FirstOrDefault(x => string.Equals(x.Name, p.Name, StringComparison.OrdinalIgnoreCase));
                if (f == null)
                {
                    throw RpcException.InvalidParams($"'{p.Name}' is not an import setting of a {plan.AssetType} (fields: {FieldNames(assetType)})");
                }
                string now = Normalise(f, p.Value);
                string old = current(f);
                if (string.Equals(now, old, StringComparison.Ordinal))
                {
                    plan.Unchanged.Add(f.Name);
                }
                else
                {
                    plan.Changes.Add(new ImportSettingChange { Field = f, NewValue = now, OldValue = old });
                }
            }
            return plan;
        }

        public static string Normalise(ImportSettingField f, JToken v)
        {
            if (f.IsBool)
            {
                if (v == null || v.Type != JTokenType.Boolean)
                {
                    throw RpcException.InvalidParams($"'{f.Name}' must be true or false");
                }
                return (bool)v ? "true" : "false";
            }
            if (v != null && v.Type == JTokenType.String)
            {
                string s = (string)v;
                for (int i = 0; i < f.EnumNames.Length; i++)
                {
                    if (string.Equals(f.EnumNames[i], s, StringComparison.OrdinalIgnoreCase))
                    {
                        return f.EnumNames[i];
                    }
                }
            }
            else if (v != null && v.Type == JTokenType.Integer)
            {
                long n = (long)v;
                for (int i = 0; i < f.EnumValues.Length; i++)
                {
                    if (f.EnumValues[i] == n)
                    {
                        return f.EnumNames[i];
                    }
                }
            }
            throw RpcException.InvalidParams($"'{f.Name}' must be one of: {string.Join(", ", f.EnumNames)} (the choices the inspector offers)");
        }

        public static JObject ToJson(string assetType)
        {
            JObject o = new JObject();
            foreach (ImportSettingField f in ForType(assetType))
            {
                JObject j = new JObject
                {
                    ["label"] = f.Label,
                    ["type"] = f.IsBool ? "bool" : "enum",
                    ["default"] = f.Default,
                    ["effect"] = f.Effect,
                };
                if (!f.IsBool)
                {
                    j["choices"] = new JArray(f.EnumNames);
                }
                o[f.Name] = j;
            }
            return o;
        }
    }

