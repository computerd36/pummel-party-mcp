    /// <summary>One import-setting field of an asset type.</summary>
    public sealed class ImportSettingField
    {
        public string AssetType;     // Texture | Prop
        public string Name;          // key in set_import_settings values
        public string Label;         // inspector label
        public string GameClass;     // class holding the member
        public string Member;        // the member the inspector edits
        public bool IsBool;
        public string EnumType;      // full type name of the game enum (checked by the drift test)
        public string EnumAssembly;  // null = Assembly-CSharp
        public string[] EnumNames;
        public long[] EnumValues;
        public string Default;
        public string Effect;
    }

