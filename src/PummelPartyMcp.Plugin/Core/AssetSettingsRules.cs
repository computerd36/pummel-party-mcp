        public static JToken ToJson(MaterialProp p, object value)
        {
            switch (p.Kind)
            {
                case MatKind.Color:
                case MatKind.ColorHdr:
                {
                    double[] c = (double[])value;
                    return new JObject { ["r"] = Round(c[0]), ["g"] = Round(c[1]), ["b"] = Round(c[2]), ["a"] = Round(c[3]) };
                }
                case MatKind.Vec2:
                {
                    double[] c = (double[])value;
                    return new JObject { ["x"] = Round(c[0]), ["y"] = Round(c[1]) };
                }
                case MatKind.Float:
                case MatKind.Range:
                    return new JValue(Round((double)value));
                case MatKind.Bool:
                    return new JValue((bool)value);
                default:
                    return value == null ? JValue.CreateNull() : new JValue((string)value);
            }
        }

        private static double Round(double d) => Math.Round(d, 6);

        public static string TypeText(MaterialProp p)
        {
            switch (p.Kind)
            {
                case MatKind.Color: return "color {r,g,b,a} 0..1";
                case MatKind.ColorHdr: return "color {r,g,b,a} 0.." + HdrMax.ToString(CultureInfo.InvariantCulture) + " (HDR)";
                case MatKind.Float: return "number" + (p.Min.HasValue ? " " + Fmt(p.Min.Value) + ".." + Fmt(p.Max.Value) : string.Empty);
                case MatKind.Range:
                    return "number (shader range" + (p.Min.HasValue ? "; documented " + Fmt(p.Min.Value) + ".." + Fmt(p.Max.Value) : "; read at run time") + ")";
                case MatKind.Texture: return "Texture asset guid or null";
                case MatKind.Mode: return "one of Opaque, Cutout, Fade, Transparent";
                case MatKind.Bool: return "bool";
                default: return "vector {x,y}";
            }
        }

        public static JObject RulesJson()
        {
            JObject o = new JObject();
            foreach (ShaderRule s in Shaders)
            {
                JObject props = new JObject();
                foreach (MaterialProp p in s.Props)
                {
                    JObject j = new JObject { ["label"] = p.Label, ["type"] = TypeText(p) };
                    if (p.ShownKey != null)
                    {
                        j["shownWhen"] = p.ShownKey + (p.ShownValue == "<texture>" ? " has a texture" : " = " + p.ShownValue);
                    }
                    if (p.Note != null)
                    {
                        j["note"] = p.Note;
                    }
                    props[p.Key] = j;
                }
                o[string.Join(" | ", s.ShaderNames)] = new JObject { ["inspector"] = s.Inspector, ["properties"] = props };
            }
            return o;
        }
