        private static double Num(JToken t, string path)
        {
            if (t == null || (t.Type != JTokenType.Integer && t.Type != JTokenType.Float))
            {
                throw RpcException.InvalidParams($"'{path}' must be a number");
            }
            double d = (double)t;
            if (double.IsNaN(d) || double.IsInfinity(d))
            {
                throw RpcException.InvalidParams($"'{path}' must be a finite number");
            }
            return d;
        }

        private static double[] Components(JToken t, string path, string[] names, int minCount, double[] defaults)
        {
            double[] r = new double[names.Length];
            Array.Copy(defaults, r, names.Length);
            if (t is JArray arr)
            {
                if (arr.Count < minCount || arr.Count > names.Length)
                {
                    throw RpcException.InvalidParams($"'{path}' must have {minCount}{(names.Length > minCount ? "-" + names.Length : "")} numbers");
                }
                for (int i = 0; i < arr.Count; i++)
                {
                    r[i] = Num(arr[i], path + "[" + i + "]");
                }
                return r;
            }
            if (t is JObject o)
            {
                foreach (JProperty p in o.Properties())
                {
                    int idx = Array.FindIndex(names, n => string.Equals(n, p.Name, StringComparison.OrdinalIgnoreCase));
                    if (idx < 0)
                    {
                        throw RpcException.InvalidParams($"'{path}.{p.Name}' is not a component (use {string.Join(", ", names)})");
                    }
                    r[idx] = Num(p.Value, path + "." + p.Name);
                }
                for (int i = 0; i < minCount; i++)
                {
                    if (o[names[i]] == null && !o.Properties().Any(p => string.Equals(p.Name, names[i], StringComparison.OrdinalIgnoreCase)))
                    {
                        throw RpcException.InvalidParams($"'{path}' needs '{names[i]}'");
                    }
                }
                return r;
            }
            throw RpcException.InvalidParams($"'{path}' must be an object {{{string.Join(", ", names)}}} or an array of numbers");
        }

        private static string Fmt(double d) => d.ToString("0.######", CultureInfo.InvariantCulture);

        private static double Clamp(MaterialPlan plan, string key, double v, double min, double max, string requested = null)
        {
            if (v < min || v > max)
            {
                double a = v < min ? min : max;
                plan.Clamped.Add(new MaterialClamp { Key = key, Requested = requested ?? Fmt(v), Applied = Fmt(a), Min = min, Max = max });
                return a;
            }
            return v;
        }

        /// <summary>
        /// Validates and normalises a properties object for a shader before anything changes. Unknown keys, keys that are not shown
        /// (their controlling field is not set accordingly in the same call or before), wrong types, unknown textures all refuse the call.
        /// </summary>
        public static MaterialPlan Plan(ShaderRule rule, JObject properties, IMaterialState state)
        {
            if (properties == null || properties.Count == 0)
            {
                throw RpcException.InvalidParams("'properties' must be an object with at least one property; properties of this shader: " + KeyList(rule));
            }
            if (properties.Count > MaxProperties)
            {
                throw RpcException.InvalidParams($"'properties' has more than {MaxProperties} entries");
            }
            MaterialPlan plan = new MaterialPlan { Rule = rule };
            foreach (JProperty jp in properties.Properties())
            {
                MaterialProp prop = rule.Props.FirstOrDefault(x => string.Equals(x.Key, jp.Name, StringComparison.OrdinalIgnoreCase));
                if (prop == null)
                {
                    throw RpcException.InvalidParams($"'{jp.Name}' is not a property of {rule.ShaderNames[0]} that the inspector offers (properties: {KeyList(rule)})");
                }
                plan.Assignments.Add(new MaterialAssignment { Prop = prop, Value = Normalise(plan, prop, jp.Value, state) });
            }
            // conditions, on the merged state (assigned values win)
            foreach (MaterialAssignment a in plan.Assignments)
            {
                MaterialProp p = a.Prop;
                if (p.ShownKey == null)
                {
                    continue;
                }
                MaterialAssignment ctl = plan.Assignments.FirstOrDefault(x => x.Prop.Key == p.ShownKey);
                object controlling = ctl != null ? ctl.Value : state.Get(p.ShownKey);
                bool shown = p.ShownValue == "<texture>" ? controlling != null : string.Equals(Convert.ToString(controlling, CultureInfo.InvariantCulture)?.ToLowerInvariant(), p.ShownValue.ToLowerInvariant(), StringComparison.Ordinal);
                if (!shown)
                {
                    throw RpcException.InvalidParams($"'{p.Key}' is only editable while {p.ShownKey} {(p.ShownValue == "<texture>" ? "has a texture" : "is " + p.ShownValue)} (the inspector hides it otherwise); set {p.ShownKey} in the same call or before");
                }
            }
            return plan;
        }

        private static string KeyList(ShaderRule rule) => string.Join(", ", rule.Props.Select(p => p.Key).ToArray());

        private static object Normalise(MaterialPlan plan, MaterialProp p, JToken v, IMaterialState state)
        {
            string path = p.Key;
            switch (p.Kind)
            {
                case MatKind.Mode:
                {
                    if (v != null && v.Type == JTokenType.String)
                    {
                        string s = (string)v;
                        string hit = Modes.FirstOrDefault(m => string.Equals(m, s, StringComparison.OrdinalIgnoreCase));
                        if (hit != null)
                        {
                            return hit;
                        }
                    }
                    else if (v != null && v.Type == JTokenType.Integer && (long)v >= 0 && (long)v < Modes.Length)
                    {
                        return Modes[(long)v];
                    }
                    throw RpcException.InvalidParams($"'{path}' must be one of: {string.Join(", ", Modes)}");
                }
                case MatKind.Bool:
                    if (v == null || v.Type != JTokenType.Boolean)
                    {
                        throw RpcException.InvalidParams($"'{path}' must be true or false");
                    }
                    return (bool)v;
                case MatKind.Float:
                {
                    double d = Num(v, path);
                    return Clamp(plan, path, d, p.Min ?? double.MinValue, p.Max ?? double.MaxValue);
                }
                case MatKind.Range:
                {
                    double d = Num(v, path);
                    double min, max;
                    if (state.TryRange(p.Key, out min, out max))
                    {
                        // the shader's own range
                    }
                    else if (p.Min.HasValue && p.Max.HasValue)
                    {
                        min = p.Min.Value;
                        max = p.Max.Value;
                    }
                    else
                    {
                        throw RpcException.InvalidParams($"'{path}': the shader's range could not be read, so the value cannot be limited as the inspector does; not set");
                    }
                    return Clamp(plan, path, d, min, max);
                }
                case MatKind.Color:
                case MatKind.ColorHdr:
                {
                    double[] c = Components(v, path, new[] { "r", "g", "b", "a" }, 3, new double[] { 0, 0, 0, 1 });
                    double max = p.Kind == MatKind.ColorHdr ? HdrMax : 1;
                    string[] n = { "r", "g", "b", "a" };
                    for (int i = 0; i < 4; i++)
                    {
                        c[i] = Clamp(plan, path + "." + n[i], c[i], 0, max);
                    }
                    return c;
                }
                case MatKind.Vec2:
                {
                    double[] c = Components(v, path, new[] { "x", "y" }, 2, new double[] { 0, 0 });
                    for (int i = 0; i < 2; i++)
                    {
                        c[i] = Clamp(plan, path + (i == 0 ? ".x" : ".y"), c[i], -1000, 1000);
                    }
                    return c;
                }
                case MatKind.Texture:
                {
                    if (v == null || v.Type == JTokenType.Null)
                    {
                        return null;
                    }
                    string guid = v.Type == JTokenType.String ? (string)v : (v is JObject o && o["guid"] != null && o["guid"].Type == JTokenType.String ? (string)o["guid"] : null);
                    if (guid == null || !Guid.TryParse(guid, out Guid g))
                    {
                        throw RpcException.InvalidParams($"'{path}' must be null (no texture), a texture asset guid, or {{guid}}");
                    }
                    string norm = g.ToString("D");
                    string why = state.CheckTexture(norm);
                    if (why != null)
                    {
                        throw RpcException.InvalidParams($"'{path}': {why}");
                    }
                    return norm;
                }
            }
            throw RpcException.Internal("unknown material property kind");
        }

