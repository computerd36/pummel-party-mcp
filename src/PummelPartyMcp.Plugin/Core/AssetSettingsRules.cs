    public static class ReferenceScan
    {
        public const int MaxFindings = 200;

        /// <summary>Finds every place in a JSON tree that holds <paramref name="guid"/> (a {guid:...} reference object or a plain string).</summary>
        public static void FindGuid(JToken token, string guid, string path, List<string> found, ref bool incomplete)
        {
            if (token == null || found.Count >= MaxFindings)
            {
                return;
            }
            switch (token.Type)
            {
                case JTokenType.Object:
                {
                    JObject o = (JObject)token;
                    // L1: {"truncatedItems": n} is the converter's marker for array items left out (MaxArrayItems).
                    // {"error": ...} is what the readers put where a value could not be read (e.g. a renamed game member): that value
                    // may hold the asset, so the scan is incomplete (a reference must never be missed).
                    if (o["truncated"] != null || o["unsupported"] != null || o["unavailable"] != null || o["truncatedItems"] != null || o["error"] != null)
                    {
                        incomplete = true;
                    }
                    JToken g = o["guid"];
                    bool self = g != null && g.Type == JTokenType.String && string.Equals((string)g, guid, StringComparison.OrdinalIgnoreCase);
                    if (self)
                    {
                        found.Add(path);
                    }
                    foreach (JProperty p in o.Properties())
                    {
                        if (self && p.Name == "guid")
                        {
                            continue;
                        }
                        FindGuid(p.Value, guid, path.Length == 0 ? p.Name : path + "." + p.Name, found, ref incomplete);
                    }
                    break;
                }
                case JTokenType.Array:
                {
                    JArray a = (JArray)token;
                    for (int i = 0; i < a.Count; i++)
                    {
                        FindGuid(a[i], guid, path + "[" + i + "]", found, ref incomplete);
                    }
                    break;
                }
                case JTokenType.String:
                    if (string.Equals((string)token, guid, StringComparison.OrdinalIgnoreCase))
                    {
                        found.Add(path);
                    }
                    break;
            }
        }

        public static JObject ToJson(AssetReference r)
        {
            JObject j = new JObject { ["kind"] = r.Kind, ["owner"] = r.Owner, ["where"] = r.Where };
            if (r.OwnerGuid != null)
            {
                j["ownerGuid"] = r.OwnerGuid;
            }
            return j;
        }

        public static string Describe(AssetReference r) =>
            $"{r.Kind} '{r.Owner}' ({r.Where})";
    }

    /// <summary>One place that can hold asset references, as the game layer read it (JSON in the plugin's converter shape, or a plain guid).</summary>
    public sealed class ReferenceSource
    {
        /// <summary>component (scene/prefab object; hits inside "actions[" become "action"), playerTrigger, material, setting, workshop.</summary>
        public string Kind;
        public string Owner;
        public string OwnerGuid;
        public JToken Data;

        /// <summary>Where to report a hit (instead of the JSON path), e.g. "get_mod_settings details.previewImage".</summary>
        public string FixedWhere;

        /// <summary>The place could not be read: the scan is incomplete (which counts as "in use").</summary>
        public bool ReadFailed;

        /// <summary>A hit here means the asset is the mod's preview image (never removed).</summary>
        public bool IsPreviewImage;
    }

    /// <summary>
    /// The reference scan behind remove_asset, get_asset references and set_import_settings (review H1): every place an asset can be
    /// referenced, re-derived from the decompiled game. The game layer turns each into <see cref="ReferenceSource"/>s; this collects
    /// the hits. Pure; tested on fake data for every location.
    /// </summary>
    public static class ReferenceCollector
    {
        /// <summary>The locations the game layer reads (docs and tests use this list).</summary>
        public static readonly string[] Locations =
        {
            "component properties of every scene object and every prefab's objects",
            "actions held by components: targets, parameters and nested Display Popup choice lists",
            "the Minigame player-settings triggers (weaponHitTrigger, tickTrigger, onDeathTrigger, onRespawnTrigger, onFirstSpawnTrigger, onRoundEndTrigger, and the hidden hitTrigger)",
            "materials' texture slots",
            "mod settings: music, ambience, preview image, board custom spaces",
            "Item mods: the item's prefabs (use, receive, held) and icon texture",
            "the Workshop item's thumbnail and preview files (read only)",
        };

        public sealed class Result
        {
            public List<AssetReference> Items = new List<AssetReference>();
            public bool Incomplete;
            public bool PreviewImage;
        }

        public static void Add(Result r, ReferenceSource s, string guid)
        {
            if (s == null)
            {
                return;
            }
            if (s.ReadFailed)
            {
                r.Incomplete = true;
                return;
            }
            List<string> found = new List<string>();
            bool incomplete = false;
            ReferenceScan.FindGuid(s.Data, guid, string.Empty, found, ref incomplete);
            if (incomplete)
            {
                r.Incomplete = true;
            }
            // ComponentReader shows some references twice: the resolved asset (PrefabReference, Prefabs[i], ItemPrefab, DroppedItemPrefab) and
            // its backing guid (PrefabGUID, PrefabGUIDs[i], ItemPrefabGUID, DroppedItemPrefabGUID). That is ONE reference: drop the guid-side hit
            // only when its partner at the same index hit; keep it when only the guid side resolves.
            if (s.Kind == "component")
            {
                foreach (string[] pair in GuidPairs)
                {
                    found.RemoveAll(f => IsPath(f, pair[1]) && found.Contains(pair[0] + f.Substring(pair[1].Length)));
                }
            }
            foreach (string path in found)
            {
                string kind = s.Kind == "component" && path.Contains("actions[") ? "action" : s.Kind;
                r.Items.Add(new AssetReference { Kind = kind, Owner = s.Owner, OwnerGuid = s.OwnerGuid, Where = s.FixedWhere ?? (path.Length == 0 ? s.Owner : path) });
                if (s.IsPreviewImage)
                {
                    r.PreviewImage = true;
                }
            }
        }

        private static readonly string[][] GuidPairs =
        {
            new[] { "PrefabReference", "PrefabGUID" },
            new[] { "Prefabs", "PrefabGUIDs" },
            new[] { "ItemPrefab", "ItemPrefabGUID" },
            new[] { "DroppedItemPrefab", "DroppedItemPrefabGUID" },
        };

        private static bool IsPath(string found, string root) =>
            found == root || found.StartsWith(root + ".", StringComparison.Ordinal) || found.StartsWith(root + "[", StringComparison.Ordinal);

        public static Result Collect(IEnumerable<ReferenceSource> sources, string guid)
        {
            Result r = new Result();
            foreach (ReferenceSource s in sources)
            {
                Add(r, s, guid);
            }
            return r;
        }
    }

